import * as React from "react"
import { cn } from "cn"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "group/card flex flex-col gap-4 overflow-hidden rounded-xl border bg-card py-6 text-sm text-card-foreground shadow-sm data-[size=sm]:gap-3 data-[size=sm]:py-4",
        className
      )}
      {...props}
    />
  )
}

